import assert from 'node:assert/strict';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { randomBytes } from 'node:crypto';
import { docker, deploy, ensureImage, resources, execute } from '../server/docker.mjs';
import { createLabEditor } from '../server/lab-editor.mjs';
import { LABEL, initialTopology, topologySchema } from '../shared/model.mjs';
import express from 'express';
import { mountWorkspaceApi } from '../server/workspace-api.mjs';
import { createProjectService, mountProjectApi } from '../server/projects.mjs';
import { fileURLToPath } from 'node:url';
const dir = await mkdtemp(path.join(os.tmpdir(), 'dtr-bridge-test-')), ui = process.argv.includes('--ui');
let topology = topologySchema.parse({ ...initialTopology(), id: 'bridge-' + Date.now().toString(36), name: 'Test temporaire — bridges Docker Tracer' });
topology.nodes[0].data.volume = '/data';
const filters = { label: [LABEL + '.project=' + topology.id] }, role = LABEL + '.role', nodeLabel = LABEL + '.node';
const legacyEngine = new Proxy(docker, { get(target, key) {
  if (key === 'createContainer') return (o) => target.createContainer({ ...o, HostConfig: { ...o.HostConfig, NetworkMode: Object.keys(o.NetworkingConfig?.EndpointsConfig || {})[0] || 'none' } });
  return typeof target[key] === 'function' ? target[key].bind(target) : target[key];
} });
let workspace, service, server, outsider;
const events = new Set();
const find = async (id) => docker.getContainer((await resources(topology)).containers.find((c) => c.Labels[nodeLabel] === id).Id);
const network = async (id) => (await resources(topology)).networks.find((n) => n.Labels[nodeLabel] === id);
const config = { engine: docker, readTopology: () => topology, persist: async (next) => { topology = next; await writeFile(path.join(dir, 'topology.json'), JSON.stringify(next)); }, ensureImage, stopCapture: async () => {} };
try {
  await deploy(topology, () => {}, legacyEngine);
  await (await find('worker')).stop({ t: 1 });
  if (ui) {
    await writeFile(path.join(dir, 'topology.json'), JSON.stringify(topology));
    const app = express(); app.use(express.json({ limit: '8mb' }));
    const emit = (e) => { for (const r of events) r.write(`data: ${JSON.stringify(e)}\n\n`); };
    app.get('/api/events', (req, res) => { res.setHeader('Content-Type', 'text/event-stream'); res.flushHeaders(); events.add(res); req.on('close', () => events.delete(res)); });
    workspace = await mountWorkspaceApi(app, { dataDir: dir, localDocker: docker, emit, labBusy: (id) => service?.hostBusy(id) || false, guardHost: (id, next) => service?.guardHost(id, next), projectList: () => service?.list() || [] });
    service = await createProjectService({ dataDir: dir, workspace, emit }); mountProjectApi(app, service);
    const dist = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../dist'); app.use(express.static(dist));
    app.get('/{*path}', (_, res) => res.sendFile(path.join(dist, 'index.html')));
    app.use((e, _req, res, _next) => res.status(e.statusCode || 400).json({ error: e.message }));
    server = app.listen(4315, '127.0.0.1'); await new Promise((r) => server.once('listening', r));
    console.log(`TEST TEMPORAIRE : http://127.0.0.1:4315 · ${topology.id} · ${dir}\nSaisir close pour nettoyer cet essai.`);
    await new Promise((resolve) => { process.stdin.resume(); process.stdin.on('data', (b) => { if (String(b).includes('close')) { process.stdin.pause(); resolve(); } }); });
  } else {
    const editor = createLabEditor(config), front = await network('frontend'), originalRedis = await (await find('redis')).inspect();
    await execute(topology, 'client', ['sh', '-c', 'printf persistent > /data/value']);
    const next = structuredClone(topology), net = next.nodes.find((n) => n.id === 'frontend');
    const subnet = front.IPAM.Config.find((p) => !p.Subnet.includes(':')).Subnet, base = subnet.split('/')[0].split('.').slice(0, 3).join('.');
    net.data.subnet = subnet;
    Object.assign(net.data.bridge, { label: 'Services web', color: '#2475a7', gateway: base + '.254', ipRange: base + '.128/25', mtu: 1400, icc: true, masquerade: true, ipv6: true, ipv6Subnet: 'fd' + randomBytes(1).toString('hex') + ':' + randomBytes(2).toString('hex') + '::/64' });
    let plan = await editor.preview(next);
    assert.deepEqual(plan.migration.services.sort(), ['client', 'web', 'worker']);
    await assert.rejects(editor.apply(plan.token), /ancienne liaison/);
    await editor.apply(plan.migration.token);
    assert.equal((await execute(topology, 'client', ['cat', '/data/value'])).output, 'persistent');
    assert.equal((await (await find('worker')).inspect()).State.Running, false);
    plan = await editor.preview(next); assert.equal(plan.blocked.length, 0); assert.equal(plan.migration, undefined);
    assert.ok(!plan.changes.some((c) => c.id === 'redis'));
    await editor.apply(plan.token);
    const changedNet = await network('frontend'); assert.notEqual(changedNet.Id, front.Id);
    assert.equal(changedNet.Options['com.docker.network.driver.mtu'], '1400'); assert.equal(changedNet.EnableIPv6, true);
    assert.equal(changedNet.IPAM.Config.find((p) => !p.Subnet.includes(':')).Gateway, base + '.254');
    assert.equal(changedNet.IPAM.Config.find((p) => !p.Subnet.includes(':')).IPRange, base + '.128/25');
    assert.equal((await execute(topology, 'client', ['wget', '-qO-', 'http://web'])).exitCode, 0);
    assert.equal((await execute(topology, 'client', ['cat', '/data/value'])).output, 'persistent');
    assert.equal((await (await find('worker')).inspect()).State.Running, false);
    const clientBefore = await (await find('client')).inspect(), webBefore = await (await find('web')).inspect();
    await execute(topology, 'client', ['sh', '-c', 'printf retained > /tmp/rollback-proof']);
    const beforeFailure = JSON.stringify(topology);
    let failOnce = true;
    const failingEngine = new Proxy(docker, { get(target, key) {
      if (key === 'createContainer') return (o) => { if (failOnce && o.Hostname === 'web') { failOnce = false; throw Error('Échec injecté après remplacement du bridge'); } return target.createContainer(o); };
      return typeof target[key] === 'function' ? target[key].bind(target) : target[key];
    } });
    const failingEditor = createLabEditor({ ...config, engine: failingEngine }), broken = structuredClone(topology);
    broken.nodes.find((n) => n.id === 'frontend').data.bridge.mtu = 1450;
    const failurePlan = await failingEditor.preview(broken);
    await assert.rejects(failingEditor.apply(failurePlan.token), (e) => e.rollback === 'restored');
    assert.equal(JSON.stringify(topology), beforeFailure);
    assert.equal((await find('client')).id, clientBefore.Id); assert.equal((await find('web')).id, webBefore.Id);
    assert.equal((await execute(topology, 'client', ['cat', '/tmp/rollback-proof'])).output, 'retained');
    assert.equal((await execute(topology, 'client', ['wget', '-qO-', 'http://web'])).exitCode, 0);
    assert.equal((await network('frontend')).Options['com.docker.network.driver.mtu'], '1400');
    assert.equal((await (await find('worker')).inspect()).State.Running, false);
    const redisAfter = await (await find('redis')).inspect(); assert.equal(redisAfter.Id, originalRedis.Id); assert.equal(redisAfter.State.StartedAt, originalRedis.State.StartedAt);
    outsider = await docker.createContainer({ name: topology.id + '-outsider', Image: 'alpine:3.23', Cmd: ['sleep', 'infinity'], Labels: { [LABEL + '.project']: topology.id, [role]: 'test-outsider' }, HostConfig: { NetworkMode: (await network('frontend')).Name } });
    await outsider.start(); assert.ok((await editor.preview(broken)).blocked.some((m) => m.includes('extérieur au labo')));
    await outsider.remove({ force: true }); outsider = null;
    const overlap = structuredClone(topology), overlapNet = overlap.nodes.find((n) => n.id === 'frontend');
    overlapNet.data.subnet = (await network('backend')).IPAM.Config[0].Subnet; overlapNet.data.bridge.gateway = ''; overlapNet.data.bridge.ipRange = '';
    assert.ok((await editor.preview(overlap)).blocked.some((m) => m.includes('recouvre')));
    console.log('Bridges : migration des anciens conteneurs, remplacement ciblé, IPv4/IPv6/MTU, volumes, DNS/HTTP, arrêt conservé, restauration après panne, autre service intact et blocages préalables : OK.');
  }
} finally {
  for (const r of events) r.end();
  if (server) await new Promise((r) => server.close(r));
  await service?.shutdown(); await workspace?.shutdown();
  if (outsider) await outsider.remove({ force: true });
  for (const c of await docker.listContainers({ all: true, filters })) await docker.getContainer(c.Id).remove({ force: true, v: false });
  for (const n of await docker.listNetworks({ filters })) await docker.getNetwork(n.Id).remove();
  for (const v of (await docker.listVolumes({ filters })).Volumes || []) await docker.getVolume(v.Name).remove();
  if (path.dirname(dir) !== os.tmpdir() || !path.basename(dir).startsWith('dtr-bridge-test-')) throw Error('Unexpected test path');
  await rm(dir, { recursive: true, force: true });
  console.log('Ressources du test de bridges nettoyées.');
}
